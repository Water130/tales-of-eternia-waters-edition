def emit_help(emit, mem, data, symbols, table, count, hint):

    # Separate from option flags, snapshots, skit input and API pointers.

    state = data + 0x1ae0

    visible = 13

    descriptor = emit('settings_description_info', f'''

        movzx eax, byte ptr {mem(data+0x1a12)}

        mov ah, byte ptr {mem(0x11c9ce8)}

        cmp ax, word ptr {mem(state)}

        je same

        mov word ptr {mem(state)}, ax

        mov word ptr {mem(state+2)}, 0

    same:

        movzx eax, al

        cmp eax, {count}

        jae empty

        shl eax, 4

        lea rcx, {mem(table)}

        add rcx, rax

        cmp byte ptr {mem(0x11c9ce8)}, 3

        je lang

        add rcx, 8

    lang:

        mov edx, dword ptr [rcx+4]

        sub edx, 2

        mov ecx, dword ptr [rcx]

        lea rax, {mem(0)}

        add rcx, rax

        ret

    empty:

        xor ecx, ecx

        xor edx, edx

        ret

    ''')

    input_rva = emit('settings_description_input', f'''

        sub rsp, 0x28

        call {descriptor:#x}

        xor eax, eax

        cmp edx, {visible}

        jbe done

        # Native 5d580/5d600 reads the second (right) stick into raw +0xc/+0x10.
        # 19dc42..19dc67 converts its Y axis to bits 24/25, with optional
        # D-pad mirroring. The left stick already feeds the low D-pad bits.
        # Use the right-stick repeat bank without changing option selection.

        mov ecx, dword ptr {mem(0x8c9188)}

        and ecx, 0x03000000

        je held

        movzx eax, word ptr {mem(state+2)}

        cmp ecx, 0x01000000

        jne down

        test eax, eax

        je consume

        dec eax

        jmp save

    down:

        cmp ecx, 0x02000000

        jne consume

        sub edx, {visible}

        cmp eax, edx

        jae consume

        inc eax

    save:

        mov word ptr {mem(state+2)}, ax

    consume:

        mov eax, 1

        jmp done

    held:

        # Suppress mirrored navigation between repeat ticks, including

        # opposite directions pressed together; never change an option.

        test dword ptr {mem(0x8c9180)}, 0x03000000

        setne al

    done:

        add rsp, 0x28

        ret

    ''')

    draw = emit('settings_description_draw', f'''

        push rbx; push rsi; push rdi; push rbp

        sub rsp, 0x28

        call {descriptor:#x}

        test rcx, rcx

        je done

        mov rsi, rcx

        mov ebp, edx

        mov ecx, dword ptr [rsi]

        lea rax, {mem(0)}

        add rcx, rax

        mov edx, 258

        mov r8d, 63

        mov r9d, -7

        mov eax, 0xffffc080

        call {symbols['settings_text']:#x}

        movzx eax, word ptr {mem(state+2)}

        mov edx, ebp

        sub edx, {visible}

        xor ecx, ecx

        test edx, edx

        cmovl edx, ecx

        cmp eax, edx

        cmova eax, edx

        mov word ptr {mem(state+2)}, ax

        sub ebp, eax

        lea rsi, [rsi+rax*4+8]

        mov edi, {visible}

        cmp edi, ebp

        cmova edi, ebp

        mov ebx, 83

    line:

        test edi, edi

        je hint

        mov ecx, dword ptr [rsi]

        lea rax, {mem(0)}

        add rcx, rax

        mov edx, 258

        mov r8d, ebx

        mov r9d, -7

        mov eax, 0xfffffdfa

        call {symbols['settings_text']:#x}

        add rsi, 4

        add ebx, 10

        dec edi

        jmp line

    hint:

        call {descriptor:#x}

        cmp edx, {visible}

        jbe done

        lea rcx, {mem(hint[0])}

        cmp byte ptr {mem(0x11c9ce8)}, 3

        je hint_lang

        lea rcx, {mem(hint[1])}

    hint_lang:

        mov edx, 258

        mov r8d, 216

        mov r9d, -6

        mov eax, 0xffffc080

        call {symbols['settings_text']:#x}

    done:

        add rsp, 0x28

        pop rbp; pop rdi; pop rsi; pop rbx

        ret

    ''')

    return draw, input_rva, state, visible
